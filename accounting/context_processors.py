def payment_destinations(request: HttpRequest) -> Dict[str, Any]:
    """
    توفير بيانات وجهات الدفع (الخزائن، البنوك، الحسابات الإلكترونية، ماكينات الفوري، ماكينات الفيزا)
    لجميع القوالب التي تحتاج خيارات الدفع.
    """
    if not request.user.is_authenticated:
        return {}
    
    try:
        from .models import Treasury, Bank, ElectronicAccount, FawryMachine, VisaMachine
        
        return {
            'payment_treasuries': Treasury.objects.filter(is_active=True).order_by('name'),
            'payment_banks': Bank.objects.filter(is_active=True).order_by('name'),
            'payment_electronic_accounts': ElectronicAccount.objects.filter(is_active=True).order_by('name'),
            'payment_fawry_machines': FawryMachine.objects.filter(is_active=True).order_by('name'),
            'payment_visa_machines': VisaMachine.objects.filter(is_active=True).order_by('name'),
        }
    except Exception:
        return {
            'payment_treasuries': [],
            'payment_banks': [],
            'payment_electronic_accounts': [],
            'payment_fawry_machines': [],
            'payment_visa_machines': [],
        }

