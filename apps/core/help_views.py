class HelpIndexView(LoginRequiredMixin, TemplateView):
    """الصفحة الرئيسية للمساعدة"""
    template_name = 'help/index.html'

    def get_context_data(self, **kwargs):
        ctx = super().get_context_data(**kwargs)
        ctx['faq_sections'] = FAQ_DATABASE
        ctx['page_title'] = 'مركز المساعدة'
        return ctx


class HelpSectionView(LoginRequiredMixin, TemplateView):
    """صفحة مساعدة قسم محدد"""
    template_name = 'help/section.html'

    def get_context_data(self, **kwargs):
        ctx = super().get_context_data(**kwargs)
        section_key = self.kwargs.get('section', 'general')
        section = FAQ_DATABASE.get(section_key, FAQ_DATABASE['general'])
        ctx['section'] = section
        ctx['section_key'] = section_key
        ctx['page_title'] = f'مساعدة — {section["title"]}'
        ctx['all_sections'] = FAQ_DATABASE
        return ctx


class HelpFAQView(LoginRequiredMixin, TemplateView):
    """صفحة الأسئلة الشائعة"""
    template_name = 'help/faq.html'

    def get_context_data(self, **kwargs):
        ctx = super().get_context_data(**kwargs)
        ctx['faq_database'] = FAQ_DATABASE
        ctx['page_title'] = 'الأسئلة الشائعة (FAQ)'

        # بحث
        query = self.request.GET.get('q', '').strip()
        if query:
            results = []
            for section_key, section in FAQ_DATABASE.items():
                for item in section['items']:
                    if query in item['q'] or query in item['a']:
                        results.append({
                            'section': section['title'],
                            'q': item['q'],
                            'a': item['a'],
                        })
            ctx['search_results'] = results
            ctx['search_query'] = query

        return ctx
